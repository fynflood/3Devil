//! PrusaSlicer's print preset. Loading a preset file at launch crashes it, but
//! a new window starts on the preset named in its settings file, so that one
//! value is changed just before opening one, as with Bambu Studio.

use std::fs;
use std::path::PathBuf;

const CONF: &str = "PrusaSlicer.ini";
/// Windows builds end the file with a checksum that an edit would break.
const CHECKSUM: &str = "# MD5 checksum";

/// Where the PrusaSlicer started by `command` keeps its settings.
fn config_dir(command: &[String]) -> Option<PathBuf> {
    if let Some(i) = command.iter().position(|a| a == "--datadir") {
        return Some(PathBuf::from(command.get(i + 1)?));
    }
    let run = command.iter().position(|a| a == "run").filter(|_| command[0].ends_with("flatpak"));
    let base = match run {
        Some(i) => {
            let app = command[i + 1..].iter().find(|a| !a.starts_with('-'))?;
            dirs::home_dir()?.join(".var/app").join(app).join("config")
        }
        None => dirs::config_dir()?,
    };
    Some(base.join("PrusaSlicer"))
}

/// The byte range of the `print` value in the `[presets]` section.
fn print_value(text: &str) -> Option<(usize, usize)> {
    let mut offset = 0;
    let mut in_presets = false;
    for line in text.split_inclusive('\n') {
        let body = line.trim_end_matches(['\r', '\n']);
        if body.trim_start().starts_with('[') {
            in_presets = body.trim() == "[presets]";
        } else if in_presets {
            if let Some((key, _)) = body.split_once('=') {
                if key.trim() == "print" {
                    let eq = body.find('=')? + 1;
                    let spaces = body[eq..].len() - body[eq..].trim_start().len();
                    return Some((offset + eq + spaces, offset + body.len()));
                }
            }
        }
        offset += line.len();
    }
    None
}

/// The settings with just the preset changed, or None if that can't be done safely.
fn with_print(text: &str, name: &str) -> Option<String> {
    if text.contains(CHECKSUM) || name.is_empty() || name.contains(['\n', '\r']) {
        return None;
    }
    let (start, end) = print_value(text)?;
    Some(format!("{}{name}{}", &text[..start], &text[end..]))
}

/// A person's own print presets: one `.ini` file each, named after the preset.
#[tauri::command]
pub fn prusa_presets(command: Vec<String>) -> Vec<String> {
    let Some(Ok(files)) = config_dir(&command).map(|d| fs::read_dir(d.join("print"))) else { return Vec::new() };
    let mut names: Vec<_> = files
        .flatten()
        .map(|f| f.path())
        .filter(|p| p.extension().is_some_and(|e| e == "ini"))
        .filter_map(|p| Some(p.file_stem()?.to_string_lossy().to_string()))
        .collect();
    names.sort();
    names
}

/// Makes `name` the preset the next new PrusaSlicer window starts on.
#[tauri::command]
pub fn set_prusa_preset(command: Vec<String>, name: String) -> Result<(), String> {
    let path = config_dir(&command).ok_or("Couldn't find PrusaSlicer's settings.")?.join(CONF);
    let text = fs::read_to_string(&path).map_err(|_| "Couldn't read PrusaSlicer's settings. Open it once first.")?;
    let edited = with_print(&text, &name).ok_or("3Devil can't set a preset in this copy of PrusaSlicer. Choose one in PrusaSlicer instead.")?;
    let scratch = path.with_extension("ini.3devil");
    fs::write(&scratch, edited).map_err(|e| e.to_string())?;
    fs::rename(&scratch, &path).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    const INI: &str = "# generated by PrusaSlicer\nprint = top level\n\n[app]\nprint = not this\nversion = 2.9\n\n[presets]\nfilament = Prusament PLA @COREONE HF0.4\nprint = 0.20mm BALANCED @COREONEL HF0.4 - Copy\nprinter = Prusa CORE One L HF0.4 nozzle\nsla_print = \n\n[recent]\nprint = nor this\n";

    fn cmd(args: &[&str]) -> Vec<String> {
        args.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn changes_only_the_preset() {
        let edited = with_print(INI, "Test").unwrap();
        assert_eq!(edited, INI.replace("print = 0.20mm BALANCED @COREONEL HF0.4 - Copy", "print = Test"));
        assert_eq!(with_print(&edited, "0.20mm BALANCED @COREONEL HF0.4 - Copy").unwrap(), INI);
    }

    #[test]
    fn keeps_windows_line_endings() {
        let crlf = INI.replace('\n', "\r\n");
        assert!(with_print(&crlf, "Test").unwrap().contains("print = Test\r\n"));
    }

    #[test]
    fn fills_an_empty_value() {
        let empty = INI.replace("print = 0.20mm BALANCED @COREONEL HF0.4 - Copy", "print = ");
        assert!(with_print(&empty, "Test").unwrap().contains("\nprint = Test\nprinter"));
    }

    #[test]
    fn leaves_what_it_should_not_touch() {
        assert_eq!(with_print(&format!("{INI}# MD5 checksum ABC\n"), "Test"), None);
        assert_eq!(with_print("[presets]\nprinter = x\n", "Test"), None);
        assert_eq!(with_print("print = top\n", "Test"), None);
        assert_eq!(with_print(INI, "two\nlines"), None);
        assert_eq!(with_print(INI, ""), None);
    }

    #[test]
    fn lists_presets_and_writes_the_choice() {
        let dir = std::env::temp_dir().join(format!("threedevil-prusa-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("print")).unwrap();
        fs::write(dir.join("print/Test.ini"), "x").unwrap();
        fs::write(dir.join("print/A, comma.ini"), "x").unwrap();
        fs::write(dir.join("print/notes.txt"), "x").unwrap();
        fs::write(dir.join(CONF), INI).unwrap();
        let command = cmd(&["prusa-slicer", "--datadir", dir.to_str().unwrap()]);
        assert_eq!(prusa_presets(command.clone()), vec!["A, comma", "Test"]);
        set_prusa_preset(command.clone(), "Test".into()).unwrap();
        assert!(fs::read_to_string(dir.join(CONF)).unwrap().contains("\nprint = Test\n"));
        assert_eq!(fs::read_dir(&dir).unwrap().count(), 2);
        fs::remove_dir_all(&dir).unwrap();
        assert!(set_prusa_preset(command.clone(), "Test".into()).is_err());
        assert!(prusa_presets(command).is_empty());
    }

    #[test]
    fn finds_the_settings_for_each_kind_of_install() {
        let home = dirs::home_dir().unwrap();
        assert_eq!(config_dir(&cmd(&["/usr/bin/prusa-slicer"])).unwrap(), dirs::config_dir().unwrap().join("PrusaSlicer"));
        assert_eq!(
            config_dir(&cmd(&["flatpak", "run", "com.prusa3d.PrusaSlicer"])).unwrap(),
            home.join(".var/app/com.prusa3d.PrusaSlicer/config/PrusaSlicer"),
        );
    }

    /// Set PRUSA_CONF to a real settings file. It's only read, and the checks
    /// report pass or fail so a failure can't print what's in it.
    #[test]
    #[ignore]
    fn real_settings_file() {
        let text = fs::read_to_string(std::env::var("PRUSA_CONF").unwrap()).unwrap();
        let (start, end) = print_value(&text).expect("no preset line");
        let current = text[start..end].to_string();
        let edited = with_print(&text, "3Devil test name").expect("couldn't edit");
        assert!(edited.lines().filter(|l| !text.contains(*l)).count() == 1, "more than one line changed");
        assert!(with_print(&edited, &current).expect("couldn't restore") == text, "not restored exactly");
    }
}
